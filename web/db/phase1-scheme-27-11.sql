INSERT INTO audit_logs (action, performed_by, user_role, details)
SELECT 'DEPLOYMENT_UNALLOTTED', 'scheme-update', 'ADMIN',
       COUNT(*) || ' officers sent back to Officer Selection: their sectors are not in the Phase-I scheme of 27-11-2026.'
  FROM sent HAVING COUNT(*) > 0;
