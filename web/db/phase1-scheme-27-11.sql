DELETE FROM zone_briefings WHERE (zone, sector) IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4'));
-- Instructions keep their other areas; one left with no area is withdrawn.
UPDATE duty_instructions d
   SET targets = (SELECT jsonb_agg(t) FROM jsonb_array_elements(d.targets) t WHERE (t->>'zone', t->>'sector') NOT IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4'))),
       updated_at = NOW()
 WHERE EXISTS (SELECT 1 FROM jsonb_array_elements(d.targets) t WHERE (t->>'zone', t->>'sector') IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4')))
   AND EXISTS (SELECT 1 FROM jsonb_array_elements(d.targets) t WHERE (t->>'zone', t->>'sector') NOT IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4')));
UPDATE duty_instructions d SET status = 'WITHDRAWN', withdrawn_at = NOW(), updated_at = NOW()
 WHERE status = 'ACTIVE'
   AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(d.targets) t WHERE (t->>'zone', t->>'sector') NOT IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4')));

-- 2. Contingency Plan Sector 5 -> Sector 4.
