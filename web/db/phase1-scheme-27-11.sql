         updated_at = NOW()
   WHERE p.pass_type = 'POLICE_FORCE' AND (p.police_zone, p.police_sector_number) IN (('Venues', 'Sector 3'), ('Routes', 'Sector 2'), ('Routes', 'Sector 3'), ('Routes', 'Sector 4'), ('Traffic', 'Sector 17'), ('Accommodations/Stay Places', 'Sector 3'), ('Contingency Plan', 'Sector 4'))
