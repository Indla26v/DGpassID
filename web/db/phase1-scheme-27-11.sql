UPDATE deployment_incharges SET sector = 'Sector 4' WHERE zone = 'Contingency Plan' AND sector = 'Sector 5';
UPDATE deployment_local_officers SET sector = 'Sector 4' WHERE zone = 'Contingency Plan' AND sector = 'Sector 5';
UPDATE zone_briefings SET sector = 'Sector 4' WHERE zone = 'Contingency Plan' AND sector = 'Sector 5';
UPDATE duty_instructions SET targets = (
  SELECT jsonb_agg(CASE WHEN t->>'zone' = 'Contingency Plan' AND t->>'sector' = 'Sector 5' THEN jsonb_set(t, '{sector}', '"Sector 4"') ELSE t END)
    FROM jsonb_array_elements(targets) t)
 WHERE targets @> '[{"zone": "Contingency Plan", "sector": "Sector 5"}]';

